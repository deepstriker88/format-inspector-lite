import test from "node:test";
import assert from "node:assert/strict";
import {DatabaseSync} from "node:sqlite";
import {createHash,randomBytes} from "node:crypto";
import {initRecovery,createRecovery} from "../src/key-recovery.js";
const hash=s=>createHash("sha256").update(s).digest("hex");
const token=p=>p+randomBytes(32).toString("base64url");
test("recovery preserves entitlement, revokes old key/code, clears old claim and fails closed",()=>{
 const db=new DatabaseSync(":memory:");
 db.exec("PRAGMA foreign_keys=ON; CREATE TABLE api_keys(id INTEGER PRIMARY KEY,key_hash TEXT UNIQUE,key_prefix TEXT,status TEXT,paddle_customer_id TEXT,paddle_subscription_id TEXT,updated_at INTEGER); CREATE TABLE activations(api_key_id INTEGER,status TEXT,paddle_customer_id TEXT,paddle_subscription_id TEXT,api_key_plain TEXT);CREATE TABLE subscription_states(subscription_id TEXT,status TEXT);CREATE TABLE usage_monthly(api_key_id INTEGER,count INTEGER);");
 initRecovery(db);initRecovery(db);
 const service=createRecovery(db,{product:"fixture",mode:"sandbox"});
 const key=token(service.keyPrefix), code=token(service.codePrefix), next=token(service.keyPrefix), nextCode=token(service.codePrefix);
 db.prepare("INSERT INTO api_keys VALUES(1,?,?,'active','ctm_fixture','sub_fixture',0)").run(hash(key),key.slice(0,16));
 db.prepare("INSERT INTO activations VALUES(1,'paid','ctm_fixture','sub_fixture',?)").run(key);
 db.exec("INSERT INTO usage_monthly VALUES(1,27)");
 assert.equal(service.enroll(token(service.keyPrefix),code).status,401);
 assert.equal(service.enroll(key,code).ok,true);
 assert.equal(service.enroll(key,nextCode).status,409);
 assert.equal(service.rotate(code,next,code).status,401);
 assert.equal(service.rotate(code,token("fixture_live_"),nextCode).status,401);
 db.exec("INSERT INTO subscription_states VALUES('sub_fixture','suspended')");
 assert.equal(service.rotate(code,next,nextCode).status,401);
 db.exec("UPDATE subscription_states SET status='active'");
 assert.equal(service.rotate(code,next,nextCode).ok,true);
 assert.equal(service.rotate(code,token(service.keyPrefix),token(service.codePrefix)).status,401);
 assert.equal(service.enroll(key,code).status,401);
 assert.equal(db.prepare("SELECT key_hash FROM api_keys").get().key_hash,hash(next));
 assert.equal(db.prepare("SELECT code_hash FROM key_recovery").get().code_hash,hash(nextCode));
 assert.equal(db.prepare("SELECT api_key_plain FROM activations").get().api_key_plain,null);
 assert.equal(db.prepare("SELECT count FROM usage_monthly").get().count,27);
 db.exec("UPDATE api_keys SET status='suspended'");
 assert.equal(service.rotate(nextCode,token(service.keyPrefix),token(service.codePrefix)).status,401);
 db.close();
});
