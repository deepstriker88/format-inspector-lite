import test from "node:test";
import assert from "node:assert/strict";
import {DatabaseSync} from "node:sqlite";
import {initAdjustments,createAdjustments} from "../src/billing-adjustments.js";
test("approved current refund/chargeback holds access; stale, partial, wrong identity and old renewal do not",()=>{
 const db=new DatabaseSync(":memory:");
 db.exec("CREATE TABLE api_keys(id INTEGER PRIMARY KEY,paddle_subscription_id TEXT,paddle_customer_id TEXT,plan TEXT);CREATE TABLE activations(api_key_id INTEGER,paddle_transaction_id TEXT,paddle_subscription_id TEXT,paddle_customer_id TEXT,status TEXT,requested_plan TEXT);INSERT INTO api_keys VALUES(1,'sub_fixture','ctm_fixture','pro');INSERT INTO activations VALUES(1,'txn_first','sub_fixture','ctm_fixture','paid','pro');");
 initAdjustments(db);initAdjustments(db);
 const svc=createAdjustments(db);
 const event={id:"adj_first",transaction_id:"txn_first",subscription_id:"sub_fixture",customer_id:"ctm_fixture",action:"refund",type:"full",status:"pending_approval"};
 const t=n=>new Date(1000*n).toISOString();
 assert.equal(svc.recordAdjustment(event,t(3)),true);assert.equal(svc.isBlocked(1),false);
 assert.equal(svc.recordAdjustment({...event,status:"approved"},t(4)),true);assert.equal(svc.isBlocked(1),true);
 assert.equal(svc.recordAdjustment(event,t(5)),false);assert.equal(svc.isBlocked(1),true);
 assert.equal(svc.recordPaid({id:"txn_first",subscription_id:"sub_fixture",customer_id:"ctm_fixture"},t(1),"pro"),true);
 assert.equal(svc.isBlocked(1),true);
 assert.equal(svc.recordPaid({id:"txn_renewal",subscription_id:"sub_fixture",customer_id:"ctm_other",origin:"subscription_recurring"},t(6),"pro"),false);
 assert.equal(svc.recordPaid({id:"txn_renewal",subscription_id:"sub_fixture",customer_id:"ctm_fixture",origin:"subscription_recurring"},t(6),"pro"),true);
 assert.equal(svc.isBlocked(1),false);
 assert.equal(svc.recordPaid({id:"txn_first",subscription_id:"sub_fixture",customer_id:"ctm_fixture"},t(7),"pro"),false);
 assert.equal(svc.isBlocked(1),false);
 const renewal={...event,id:"adj_second",transaction_id:"txn_renewal",type:"partial",status:"approved"};
 svc.recordAdjustment(renewal,t(8));assert.equal(svc.isBlocked(1),false);
 svc.recordAdjustment({...renewal,id:"adj_other",customer_id:"ctm_other",type:"full"},t(9));assert.equal(svc.isBlocked(1),false);
 const dispute={...renewal,id:"adj_dispute",action:"chargeback"};
 svc.recordAdjustment(dispute,t(10));assert.equal(svc.isBlocked(1),true);
 svc.recordAdjustment({...dispute,status:"reversed"},t(11));assert.equal(svc.isBlocked(1),false);
 svc.recordAdjustment(dispute,t(12));assert.equal(svc.isBlocked(1),false);
 db.close();
});
